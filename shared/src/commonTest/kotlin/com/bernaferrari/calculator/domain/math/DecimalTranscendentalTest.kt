    private fun assertEncloses(
        expression: String, lower: String, upper: String, retry: Boolean = false, angle: AngleUnit = AngleUnit.DEGREES,
    ) {
        val value = CalcEngine.evaluateValue(expression, angle,
            displaySettled = if (retry) ({ false }) else null, timeBudgetMillis = 4_000)
        val radius = assertNotNull(value.error, expression)
        assertTrue(value.v.subtract(radius) <= Decimal(lower), "$expression missed the lower reference bound")
        assertTrue(value.v.add(radius) >= Decimal(upper), "$expression missed the upper reference bound")
        if (retry) assertTrue(value.v.precision() >= 150, "$expression did not reach the 160-digit pass")
    }

