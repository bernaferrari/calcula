    @Test fun seededTrigIntervalsOverlapAtFortyAndOneHundredSixtyDigits() {
        val random = Random(98431)
        repeat(18) { index ->
            val digits = random.nextInt(5, 260)
            val coefficient = random.nextInt(1, 9999)
            val (expression, angle) = when (index % 3) {
                0 -> "sin(${coefficient}E$digits)" to AngleUnit.RADIANS
                1 -> "tan(90−${coefficient}E−${random.nextInt(10, 28)})" to AngleUnit.DEGREES
                else -> "cos(${coefficient}E−${random.nextInt(13, 35)})−1" to AngleUnit.RADIANS
            }
            val normal = CalcEngine.evaluateValue(expression, angle, timeBudgetMillis = 4_000)
            val refined = CalcEngine.evaluateValue(expression, angle, requestedDigits = 148, timeBudgetMillis = 4_000)
            val normalRadius = assertNotNull(normal.error, expression)
            val refinedRadius = assertNotNull(refined.error, expression)
            assertTrue(normal.v.subtract(refined.v).abs() <= normalRadius.add(refinedRadius), expression)
            assertTrue(refinedRadius < normalRadius, "$expression did not gain precision")
        }
    }

    @Test fun randomizedIntervalsOverlapAtFortyAndOneHundredSixtyDigits() {
        val random = Random(42)
        repeat(18) { index ->
            val sign = if (random.nextBoolean()) "+" else "−"
            val offset = "${random.nextInt(1, 10)}E−${random.nextInt(2, 100)}"
            val expression = if (index % 3 == 0) "(1$sign$offset)^0.375" else "ln(1$sign$offset)"
            val normal = CalcEngine.evaluateValue(expression, AngleUnit.DEGREES)
            val refined = CalcEngine.evaluateValue(expression, AngleUnit.DEGREES,
                displaySettled = { false }, timeBudgetMillis = 2_000)
            val normalRadius = assertNotNull(normal.error, expression)
            val refinedRadius = assertNotNull(refined.error, expression)
            assertTrue(normal.v.subtract(refined.v).abs() <= normalRadius.add(refinedRadius), expression)
        }
    }

